#!/usr/bin/env node
/**
 * ZERO FLARE — publish the open corpus mirror for the Cloudflare edge.
 *
 * Copies the immutable, SHA-256-verified ingest ledgers and the knowledge
 * registries into public/corpus/ so that:
 *   1. the edge runtime can read the baseline via its ASSETS binding
 *      (see src/lib/ingest/storage.ts), and
 *   2. judges can download the exact open-data extracts the platform runs on
 *      straight from the deployed site (Best Use of Data transparency).
 *
 * Run before `opennextjs-cloudflare build` / `deploy` (wired into the
 * build:cf / deploy:cf npm scripts).
 */
import { cpSync, existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.dirname(path.dirname(path.dirname(fileURLToPath(import.meta.url))));
const SRC = [
  { from: "data/ingest", to: "public/corpus/data/ingest" },
  { from: "data/experiments", to: "public/corpus/data/experiments" },
  { from: "data/ml", to: "public/corpus/data/ml" },
  { from: "knowledge", to: "public/corpus/knowledge" },
  { from: "paper-figures", to: "public/corpus/paper-figures" },
];

let total = 0;
rmSync(path.join(ROOT, "public/corpus"), { recursive: true, force: true });
for (const { from, to } of SRC) {
  const src = path.join(ROOT, from);
  if (!existsSync(src)) {
    console.warn(`[sync-corpus] missing ${from} — skipped`);
    continue;
  }
  const dst = path.join(ROOT, to);
  mkdirSync(path.dirname(dst), { recursive: true });
  cpSync(src, dst, { recursive: true });
  console.log(`[sync-corpus] ${from} → ${to}`);
  total += 1;
}

writeFileSync(
  path.join(ROOT, "public/corpus/README.md"),
  `# Open corpus mirror\n\nStatic, immutable mirror of the platform's canonical open-data extracts,\npublished so every number on the site can be re-derived from these files\n(Best Use of Data transparency).\n\nMirrored layers: data/ingest (acquisition ledger, batch receipts, PSI\nmetadata, media index), data/experiments (recovered PSI tables), data/ml\n(model experiments), knowledge (entities + BM25 text index).\n\nSHA-256 provenance for each artifact lives in data/ingest/audit.json and\ndocs/CANONICAL_DATA_MANIFEST.json.\n\nGenerated by scripts/cloudflare/sync-corpus.mjs — do not edit by hand.\n`,
);
console.log(`[sync-corpus] done — ${total} layer(s) mirrored into public/corpus`);
