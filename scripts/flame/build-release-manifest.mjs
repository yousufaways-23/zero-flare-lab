#!/usr/bin/env node
/**
 * ZERO FLARE — release manifest generator (research doc §8.1).
 * Single source of truth for corpus counts, registry sizes, model versions,
 * build identity and the canonical production URL. Consumed by README, the
 * audit notebook and release verification — never hand-edited.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const read = (p) => JSON.parse(readFileSync(path.join(ROOT, p), "utf8"));

function containedRead(p) {
  const rp = path.resolve(ROOT, p);
  if (rp !== ROOT && !rp.startsWith(ROOT + path.sep)) throw new Error(`path escapes repo root: ${p}`);
  return readFileSync(rp, "utf8");
}

let gitCommit = null;
let gitBranch = null;
try {
  gitCommit = execFileSync("git", ["rev-parse", "HEAD"], { cwd: ROOT, shell: false }).toString().trim();
  gitBranch = execFileSync("git", ["rev-parse", "--abbrev-ref", "HEAD"], { cwd: ROOT, shell: false }).toString().trim();
} catch { /* git unavailable — record null honestly */ }

const corpus = read("src/data/generated/corpus.json");
const expReg = read("src/data/generated/experiment_datasets.json");
const investigations = read("src/data/generated/investigations.json");
const mathModels = read("src/data/generated/mathematical_models.json");
const eqTs = containedRead("src/lib/science/equations.ts");
const toolsTs = containedRead("src/lib/agent/tools.ts");

const equationCount = (containedRead("src/lib/science/equations.ts").match(/^  eq\(/gm) || []).length;
const toolCount = (toolsTs.match(/^    name: "[a-z_]+"/gm) || []).length;
const equationTests = (eqTs.match(/expect:/g) || []).length;

const cards = {};
for (const p of [
  "models/flex-extinction/v2/model_card.json",
  "models/cfig-hot-ignition/v1/model_card.json",
  "models/spice-flame-duration/v1/model_card.json",
]) {
  if (existsSync(path.join(ROOT, p))) {
    const c = read(p);
    cards[c.model_id || p] = { status: c.status ?? null, metrics: c.metrics ?? null };
  }
}

const flexExp = existsSync(path.join(ROOT, "data/ml/flex_extinction_experiment.json"))
  ? read("data/ml/flex_extinction_experiment.json")
  : null;

const manifest = {
  generatedAt: new Date().toISOString(),
  productionUrl: (process.env.ZERO_FLARE_PROD_URL || "https://zero-flare.yousuf-aways.workers.dev").replace(/\/$/, ""),
  build: { commit: gitCommit, branch: gitBranch },
  corpus: {
    investigations: investigations.investigations.length,
    tables: corpus.totals.tables,
    rows: corpus.totals.rows,
    columns: corpus.totals.columns,
    duplicateRows: corpus.totals.duplicateRows,
    parseFailures: corpus.totals.parseFailures,
    experimentDatasets: expReg.experiment_count,
  },
  registries: { equations: equationCount, equationReferenceCases: equationTests, agentTools: toolCount, mathematicalModels: mathModels.models.length },
  models: cards,
  ml: flexExp
    ? {
        experimentId: flexExp.experiment_id,
        championDecision: flexExp.championDecision ?? null,
        note: "metrics live in the model card + experiment log; this manifest records identity only",
      }
    : null,
  notes: [
    "This file is GENERATED by scripts/flame/build-release-manifest.mjs — do not hand-edit.",
    "Counts are recomputed from the bundled artifacts at build time.",
  ],
};

mkdirSync(path.join(ROOT, "docs", "data-audit"), { recursive: true });
writeFileSync(path.join(ROOT, "docs", "data-audit", "release-manifest.json"), JSON.stringify(manifest, null, 1) + "\n", "utf8");
console.log("release manifest written:", manifest.corpus, manifest.registries);
