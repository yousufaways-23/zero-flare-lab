function MiniCalculator({ equation }: { equation: Equation }) {
  const [inputs, setInputs] = useState<Record<string, string>>({});
  const [result, setResult] = useState<CalculationResult | null>(null);
  const [error, setError] = useState<string | null>(null);

  const run = () => {
    const clean: Record<string, number> = {};
    for (const [k, v] of Object.entries(inputs)) {
      const n = v.trim() === "" ? NaN : Number(v);
      if (Number.isFinite(n)) clean[k] = n;
    }
    try {
      setResult(runCalculation(equation.id, clean));
      setError(null);
    } catch (e) {
      setResult(null);
      setError(e instanceof Error ? e.message : String(e));
    }
  };

  return (
    <div className="rounded-md border border-[color:var(--research-foreground)]/15 bg-[color:var(--research-muted)] p-3">
      <p className="flex items-center gap-1.5 text-[11px] font-semibold">
        <Calculator className="h-3.5 w-3.5" aria-hidden /> Try it (deterministic engine)
      </p>
      <div className="mt-2 grid gap-2 sm:grid-cols-2">
        {equation.variables.map((v) => (
          <div key={v.key} className="min-w-0">
            <label htmlFor={`mini-${equation.id}-${v.key}`} className="flex flex-wrap items-baseline gap-x-1 text-[10px] font-medium">
              <span className="font-mono">{v.symbol}</span>
              <span className="text-muted-foreground">{v.label} [{v.unit}]</span>
            </label>
            <Input
              id={`mini-${equation.id}-${v.key}`}
              type="text"
              inputMode="decimal"
              className="mt-1 h-7 font-mono text-[11px]"
              placeholder="required"
              value={inputs[v.key] ?? ""}
              onChange={(e) => setInputs((prev) => ({ ...prev, [v.key]: e.target.value }))}
            />
          </div>
        ))}
      </div>
      <Button size="sm" className="mt-2.5 h-7 text-[11px]" onClick={run}>
        <Sigma className="mr-1 h-3 w-3" aria-hidden /> Calculate
      </Button>
      {error ? (
        <p className="mt-2 rounded border border-destructive/40 bg-destructive/10 p-2 text-[11px] leading-snug text-red-500" role="alert">{error}</p>
      ) : null}
      {result ? (
        <div className="mt-2 rounded border border-primary/30 bg-primary/5 p-2">
          <p className="font-mono text-sm font-semibold text-[color:var(--research-foreground)]">
            {fmtNum(result.value)} <span className="text-[11px] font-normal text-muted-foreground">{result.unit}</span>
          </p>
          <p className="text-[10px] text-muted-foreground">{result.label}</p>
          {result.warnings.map((w, i) => (
            <p key={i} className="mt-1 text-[10px] text-amber-600">warning: {w}</p>
          ))}
        </div>
      ) : null}
    </div>
  );
}

